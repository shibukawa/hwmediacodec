// SetBlob writes a byte array attribute.
func (a *IMFAttributes) SetBlob(key *GUID, data []byte) HRESULT {
	var p *byte
	if len(data) > 0 {
		p = &data[0]
	}
	r, _, _ := syscall.SyscallN(a.vtbl.SetBlob, uintptr(unsafe.Pointer(a)), uintptr(unsafe.Pointer(key)), uintptr(unsafe.Pointer(p)), uintptr(len(data)))
	return hres(r)
}
