// TestOpensBundledClip runs the first Update's work (probe, demux, open the
// decoder) without a window, the way the mobile view controller will.
func TestOpensBundledClip(t *testing.T) {
	ctx := context.Background()
	if !hwmediacodec.HasHardware(ctx, hwmediacodec.HEVC, hwmediacodec.Decode) {
		t.Skip("no hardware HEVC decoder on this machine")
	}
	g := newGame()
	g.open()
	defer g.Close()
	if g.err != nil {
		t.Fatalf("open: %v", g.err)
	}
	if g.player == nil || g.vw == 0 || g.vh == 0 {
		t.Fatalf("no player or picture size after open: %+v", g)
	}
	if g.info == "" {
		t.Error("the probe summary is empty")
	}
	t.Log(g.info)
}

// TestCheckStages runs the check mode's stages without a window: the
// automatic checks, the playback stage (skipped through) and the report
// with the mobile wording.
func TestCheckStages(t *testing.T) {
	SetDeviceInfo("TestPhone1,1, TestOS 1.0")
	defer SetDeviceInfo("")
	c := newCheck()
	defer c.close()
	deadline := time.Now().Add(5 * time.Minute)
	for !c.autoDone.Load() {
		if time.Now().After(deadline) {
			t.Fatal("the automatic checks did not finish")
		}
		time.Sleep(100 * time.Millisecond)
	}
	c.startPlayback()
	for c.stage == ckPlayback {
		c.pb.Skip()
		c.pb.Update()
		if c.pb.Done() {
			c.finish()
		}
	}
	if c.stage != ckDone {
		t.Fatalf("stage %d", c.stage)
	}
	md := c.r.Markdown()
	for _, want := range []string{"- Device: TestPhone1,1, TestOS 1.0\n", "### Decode", "_Generated by the check mode of the mobile sample"} {
		if !strings.Contains(md, want) {
			t.Errorf("report lacks %q:\n%s", want, md)
		}
	}
	for _, sz := range [][2]int{{820, 1180}, {1180, 820}} {
		if c.layout(sz[0], sz[1]); c.scale != 2 || c.w != sz[0]/2 || c.h != sz[1]/2 {
			t.Errorf("tablet %dx%d: interface %dx%d at scale %d", sz[0], sz[1], c.w, c.h, c.scale)
		}
	}
	if c.layout(402, 874); c.scale != 1 {
		t.Errorf("phone scale %d", c.scale)
	}
}
