func TestReportMarkdown(t *testing.T) {
	r := NewReport()
	r.SetProbe([]hwmediacodec.Capability{
		{Backend: "mediafoundation", Codec: hwmediacodec.H264, Direction: hwmediacodec.Decode, Hardware: true},
		{Backend: "mediafoundation", Codec: hwmediacodec.H264, Direction: hwmediacodec.Encode, Hardware: true,
			Device: "AMD Radeon(TM) Graphics (AMDh264Encoder)"},
		{Backend: "mediafoundation", Codec: hwmediacodec.AAC, Direction: hwmediacodec.Decode},
	}, nil)
	if b := r.Backend(hwmediacodec.H264, hwmediacodec.Encode); b != "mediafoundation" {
		t.Errorf("Backend: %q", b)
	}
	r.Set(r.Add("Encode", "H.264 encode / mediafoundation"), Failed, "frame 3: a | b\nc")
	r.Set(r.Add("Decode", "H.264 decode / mediafoundation"), Passed, "293 frames")
	md := r.Markdown()
	for _, want := range []string{
		"## Check report: ", "(mediafoundation), 1 passed, 1 failed",
		"| mediafoundation | h264 | encode | true |  | AMD Radeon(TM) Graphics (AMDh264Encoder) |",
		"- GPU: AMD Radeon(TM) Graphics; driver: _(please fill in",
		"| H.264 encode / mediafoundation | FAIL | frame 3: a \\| b c |",
		"_Generated by `go run github.com/shibukawa/hwmediacodec/examples/check@latest`._\n",
	} {
		if !strings.Contains(md, want) {
			t.Errorf("report lacks %q:\n%s", want, md)
		}
	}
	if strings.Index(md, "### Decode") > strings.Index(md, "### Encode") {
		t.Error("sections out of order")
	}
	link, full := r.IssueURL()
	if !full {
		t.Fatal("a short report does not fit the link")
	}
	u, err := url.Parse(link)
	if err != nil {
		t.Fatal(err)
	}
	if q := u.Query(); len(q) != 2 || !strings.HasPrefix(q.Get("title"), "Check report: ") || q.Get("body") != md {
		t.Errorf("issue URL %s does not carry the title and the report", u)
	}
	for range 200 {
		r.Set(r.Add("Decode", "a long check name for a long report"), Passed, "%s", strings.Repeat("detail ", 10))
	}
	if link, full := r.IssueURL(); full || len(link) > MaxIssueURL || !strings.Contains(link, "too+long") {
		t.Errorf("a long report gives a %d-byte link (full %v)", len(link), full)
	}
}

// TestReportDevice is the wording of the mobile check.
func TestReportDevice(t *testing.T) {
	r := NewReport()
	r.Generator, r.Device, r.PasteHint = "the check mode of examples/mobile", "iPhone16,1, iOS 26.0", "paste it"
	md := r.Markdown()
	if !strings.Contains(md, "- Device: iPhone16,1, iOS 26.0\n\n### Probe") || strings.Contains(md, "GPU / driver") ||
		!strings.Contains(md, "_Generated by the check mode of examples/mobile._") {
		t.Errorf("report:\n%s", md)
	}
	for range 200 {
		r.Set(r.Add("Decode", "a long check name for a long report"), Passed, "%s", strings.Repeat("detail ", 10))
	}
	if link, full := r.IssueURL(); full || !strings.HasSuffix(link, "&body=paste+it") {
		t.Errorf("long report link %s", link)
	}
}

func TestHalve(t *testing.T) {
	const w, h = 720, 1280
	y := make([]byte, w*h)
	uv := make([]byte, w*h/2)
	for i := range y {
		y[i] = byte(i % w / 3)
	}
	for i := range uv {
		uv[i] = byte(i % 2 * 255)
	}
	f := &hwmediacodec.Frame{Width: w, Height: h, Format: hwmediacodec.NV12, Planes: [][]byte{y, uv}, Strides: []int{w, w}}
	s := halve(f, 2)
	if s.Width != srcW || s.Height != srcH || len(s.Planes[0]) != srcW*srcH || len(s.Planes[1]) != srcW*srcH/2 || s.PTS != 2*srcTick {
		t.Fatalf("halved to %dx%d with %d/%d bytes, PTS %d", s.Width, s.Height, len(s.Planes[0]), len(s.Planes[1]), s.PTS)
	}
	// The crop drops 4 columns on each side of the halved picture, so
	// column c averages source columns 2c+8 and 2c+9 of rows 0 and 1.
	if got, want := s.Planes[0][10], byte((2*int(y[28])+2*int(y[29])+2)/4); got != want {
		t.Errorf("luma %d, want %d", got, want)
	}
	if s.Planes[1][0] != 0 || s.Planes[1][1] != 255 {
		t.Errorf("chroma %d %d: U and V swapped", s.Planes[1][0], s.Planes[1][1])
	}
	if p := lumaPSNR(s, s); p != 99 {
		t.Errorf("PSNR of a picture with itself %.1f", p)
	}
	if synth := synthFrames(); len(synth) != srcFrames || flat(synth[0]) {
		t.Error("synthetic pictures are missing or flat")
	}
}

// TestPlaybackAnswers walks the stage through the answers without a
// window: a decoder for the clip is needed, so it runs where one is.
func TestPlaybackAnswers(t *testing.T) {
	r := NewReport()
	caps, err := hwmediacodec.Probe(t.Context())
	if err != nil {
		t.Fatal(err)
	}
	r.SetProbe(caps, nil)
	p := NewPlayback(r, 0, false)
	defer p.Close()
	if p.Done() {
		t.Skip("no decoder for the bundled clip on this machine")
	}
	first := p.Codec()
	p.Answer(true) // still watching: ignored
	if len(r.Snapshot()) != 0 {
		t.Fatal("an answer while watching was recorded")
	}
	p.Update()
	if p.Question() != AskPicture {
		t.Fatalf("question %d after the play time", p.Question())
	}
	p.Answer(true)
	if p.Player() != nil && p.Player().HasAudio() && p.Question() != AskSound {
		t.Fatalf("no sound question for a clip with audio")
	}
	if p.Question() == AskSound {
		p.Answer(false)
	}
	for !p.Done() {
		p.Skip()
	}
	res := r.Snapshot()
	if want := CodecName(first) + " picture / " + r.Backend(first, hwmediacodec.Decode); res[0].Name != want || res[0].Status != Passed {
		t.Errorf("first result %+v", res[0])
	}
	if res[1].Name == "Sound (AAC)" && res[1].Status != Failed {
		t.Errorf("sound result %+v", res[1])
	}
	for _, x := range res[2:] {
		if x.Status != Skipped {
			t.Errorf("result %+v after Skip", x)
		}
	}
}

